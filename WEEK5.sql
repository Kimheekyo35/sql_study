CREATE VIEW VORDERS
AS SELECT ORDERID, O.CUSTID, NAME, O.BOOKID, BOOKNAME, SALEPRICE, ORDERDATE
FROM ORDERS O, BOOK B, CUSTOMER C
WHERE C.CUSTID=O.CUSTID AND B.BOOKID=O.BOOKID;

